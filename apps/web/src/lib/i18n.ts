export type { Lang };

/** The strings of each language. English has every one; another language may lack some. */
const TEXTS: Texts<Key> = { en, de };

const LANG_KEY = "wizards.lang";
/** The last language other than English the person picked: the switch's other side. */
const LOCAL_KEY = "wizards.lang.local";

/**
 * The language engenty's other pages read and keep — the account pages and the mails their
 * server sends: a readable cookie on the site's parent domain holding a language code
 * (engenty-wizards-manage, apps/server/src/mails/lang.ts).
 */
const SHARED_COOKIE = "engenty_lang";

function sharedLang(): Lang | null {
  if (typeof document === "undefined") {
    return null;
  }
  const raw = document.cookie
    .split(";")
    .map((part) => part.trim())
    .find((part) => part.startsWith(`${SHARED_COOKIE}=`))
    ?.slice(SHARED_COOKIE.length + 1);
  return isLang(raw) ? raw : null;
}

function shareLang(next: Lang) {
  if (typeof document === "undefined") {
    return;
  }
  const host = window.location.hostname;
  const labels = host.split(".");
  // app.engenty.ai → engenty.ai, engenty.ai stays itself: one cookie the account pages share.
  // localhost and plain addresses keep the host.
  const named = labels.length > 1 && !/^\d+$/.test(labels[labels.length - 1]);
  const parent = named ? (labels.length > 2 ? labels.slice(1).join(".") : host) : "";
  const secure = window.location.protocol === "https:" ? "; Secure" : "";
  // biome-ignore lint/suspicious/noDocumentCookie: the Cookie Store API is missing in Safari and Firefox
  document.cookie = `${SHARED_COOKIE}=${next}; Path=/; Max-Age=${60 * 60 * 24 * 365}; SameSite=Lax${parent ? `; Domain=${parent}` : ""}${secure}`;
}

function kept(key: string): Lang | null {
  try {
    const pick = localStorage.getItem(key);
    return isLang(pick) ? pick : null;
  } catch {
    return null;
  }
}

/** The language this browser kept from the person's last pick; null where they never picked. */
export function storedLang(): Lang | null {
  return kept(LANG_KEY);
}

/**
 * This browser's own language beside English (`localLang`): from its languages, else from the
 * country of its time zone; null where neither names one engenty speaks.
 */
function browserLang(): Lang | null {
  if (typeof navigator === "undefined") {
    return null;
  }
  let zone: string | null = null;
  try {
    zone = Intl.DateTimeFormat().resolvedOptions().timeZone;
  } catch {
    // no time zone to go by
  }
  return localLang(navigator.languages ?? [navigator.language], zone);
}

/**
 * The language in effect: the person's pick, else the local language of this browser, else
 * English. It changes when the person switches, so read it where it is used — while rendering
 * or in a function — never once at the top of a module.
 */
export let lang: Lang = storedLang() ?? sharedLang() ?? browserLang() ?? "en";

/** The person's own pick (or this browser's language): what `lang` goes back to after a page. */
let picked: Lang = lang;

/**
 * The language this browser reads, for a wizard translated on request: any language, from the
 * browser's languages, else the country of its time zone (`viewerLang`).
 */
export function viewerLang(): string | null {
  if (typeof navigator === "undefined") {
    return null;
  }
  let zone: string | null = null;
  try {
    zone = Intl.DateTimeFormat().resolvedOptions().timeZone;
  } catch {
    // no time zone to go by
  }
  return viewerLangOf(navigator.languages ?? [navigator.language], zone);
}

/**
 * The language the switch offers beside English: the one in effect when it is not English,
 * else the last other one the person picked, else this browser's; null where there is none —
 * then the studio speaks English and shows no switch.
 */
export function localSide(): Lang | null {
  if (lang !== "en") {
    return lang;
  }
  return kept(LOCAL_KEY) ?? browserLang();
}

const listeners = new Set<() => void>();
/** Counts every change: a page's table can change while `lang` stays the same. */
let version = 0;

/** Switches the language in place and keeps the pick: the app renders again, nothing reloads. */
export function setLang(next: Lang) {
  shareLang(next);
  picked = next;
  if (next === lang) {
    return;
  }
  lang = next;
  // The runner's own words follow.
  setRunnerLang(next);
  document.documentElement.lang = next;
  try {
    localStorage.setItem(LANG_KEY, next);
    if (next !== "en") {
      localStorage.setItem(LOCAL_KEY, next);
    }
  } catch {
    // the pick only lasts this page then
  }
  version += 1;
  for (const listener of listeners) {
    listener();
  }
}

/**
 * A page in a language of its own (a wizard's page: its language, or the one it is translated
 * into), without touching the person's pick: one of `LANGS` speaks its own strings, any other
 * the runner's words from `table`, the rest in English. Null goes back to the pick.
 */
export function showLang(code: string | null, table?: RunnerTable | null) {
  const next: Lang = code === null ? picked : isLang(code) ? code : "en";
  const other = code !== null && !isLang(code) ? (table ?? null) : null;
  if (next === lang && other === runnerTable()) {
    return;
  }
  lang = next;
  setRunnerLang(next);
  setRunnerTable(other);
  document.documentElement.lang = code ?? next;
  version += 1;
  for (const listener of listeners) {
    listener();
  }
}

/** The language, for a component that must render again when it changes — the app's root does. */
export function useLang(): Lang {
  useSyncExternalStore(
    (listener) => {
      listeners.add(listener);
      return () => listeners.delete(listener);
    },
    () => version,
  );
  return lang;
}

/** What a run reports, in the language the person reads: its note where it has one. */
export function eventText(ev: { message: string; note?: RunNote | null }): string {
  const table = runnerTable();
  return (ev.note && noteText(ev.note, table?.lang ?? lang, table?.notes)) || ev.message;
}

/** A string in the language in effect: its plural form by `{count}` or `{n}`, its gaps filled. */
export function t(key: Key, vars?: Record<string, string | number>): string {
  // A page in a translated language: the runner's words from its table.
  const table = runnerTable();
  const own = table?.runner[key];
  if (table && own !== undefined) {
    return lineText(own, table.lang, vars);
  }
  return textOf(TEXTS, key, lang, vars);
}

