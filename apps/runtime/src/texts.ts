export const SERVER_TEXTS: Texts<ServerKey> = { en: EN, de: DE };

/** A line of the server's table in a language; English where the language lacks it. */
export function serverText(
  lang: Lang,
  key: ServerKey,
  params?: Record<string, Gap | undefined>,
): string {
  return textOf(SERVER_TEXTS, key, lang, params);
}
